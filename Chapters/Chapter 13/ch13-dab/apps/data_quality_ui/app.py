"""Data Quality UI - Databricks App for the data quality agent.

Calls the data-quality-agent serving endpoint and displays the generated
rules. The endpoint, catalog, and schema come from environment variables
set in the DAB app definition, so the same code runs in every environment.
Authentication is handled by the Databricks Apps runtime; no credentials
are needed in code.
"""

import json
import os

import pandas as pd
import streamlit as st
from databricks.sdk import WorkspaceClient

MODEL_ENDPOINT = os.environ.get("MODEL_ENDPOINT", "data-quality-agent-endpoint")
UC_CATALOG = os.environ.get("UC_CATALOG", "dev_catalog")
UC_SCHEMA = os.environ.get("UC_SCHEMA", "finance")

st.set_page_config(page_title="Data Quality Rules", layout="wide")
st.title("Data Quality Rule Generator")
st.caption(
    f"Calls the `{MODEL_ENDPOINT}` serving endpoint. "
    "Rules are generated by the registered data quality agent."
)

with st.sidebar:
    st.header("Target table")
    table = st.text_input("Table", "sales_transactions")
    catalog = st.text_input("Catalog", "demo")
    schema = st.text_input("Schema", "finance")

if st.button("Generate rules", type="primary"):
    with st.spinner("Calling the agent..."):
        try:
            workspace = WorkspaceClient()
            response = workspace.serving_endpoints.query(
                name=MODEL_ENDPOINT,
                dataframe_records=[{
                    "table_name": table,
                    "catalog": catalog,
                    "schema": schema,
                }],
            )
            predictions = response.predictions
            rules_payload = predictions[0]["rules"] if isinstance(
                predictions, list) else predictions["rules"].iloc[0]
            rules = json.loads(rules_payload)

            if not rules:
                st.warning("The agent produced no rules for this table.")
            else:
                st.success(f"Generated {len(rules)} rules")
                st.dataframe(pd.DataFrame(rules), use_container_width=True)

                st.subheader("SQL checks")
                for rule in rules[:5]:
                    st.code(
                        "SELECT COUNT(*) AS violations "
                        f"FROM {catalog}.{schema}.{table} "
                        f"WHERE NOT ({rule['rule']});",
                        language="sql",
                    )
        except Exception as exc:
            st.error(f"The agent call failed: {exc}")
else:
    st.info("Choose a table and select **Generate rules**.")
